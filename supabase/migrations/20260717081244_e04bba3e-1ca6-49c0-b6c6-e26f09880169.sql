2. Kuttu Ka Atta Roti (Traditional Pakistani Buckwheat Roti)
────────────────────────────
A staple during fasting days and a diabetic-friendly alternative to wheat roti.

Ingredients
- 2 cups Tartary buckwheat flour (kuttu ka atta)
- 1 medium boiled potato, mashed
- 1/2 tsp salt (or sendha namak)
- Warm water as needed

Method
1. Mix flour, mashed potato and salt. Add warm water slowly to form a soft dough.
2. Divide into balls and roll between two sheets of butter paper (buckwheat dough is delicate).
3. Cook on a hot tawa with a little ghee until golden spots appear on both sides.
4. Serve with dahi, aloo ki sabzi or lauki curry.

