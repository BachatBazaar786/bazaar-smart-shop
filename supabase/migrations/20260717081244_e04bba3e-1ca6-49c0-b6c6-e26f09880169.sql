1. Fluffy Himalayan Tartary Buckwheat Pancakes
────────────────────────────
The most popular way to use Tartary buckwheat flour worldwide — soft, nutty pancakes that stay gluten-free.

Ingredients
- 1 cup Himalayan Tartary Buckwheat flour
- 1 cup milk (or almond milk)
- 1 egg
- 1 tbsp honey or shakkar
- 1 tsp baking powder
- Pinch of salt
- 1 tbsp ghee or butter (for the pan)

Method
1. Whisk milk, egg and honey together.
2. Add buckwheat flour, baking powder and salt. Rest the batter for 5 minutes.
3. Cook small pancakes on a hot, lightly greased tawa, 2 minutes per side.
4. Serve with honey, fresh fruit or a drizzle of desi ghee.

