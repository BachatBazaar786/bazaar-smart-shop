7. Buckwheat Chocolate Chip Cookies (Gluten-Free)
────────────────────────────
A modern favorite kids love.

Ingredients
- 1.5 cups Tartary buckwheat flour
- 1/2 cup butter, softened
- 1/2 cup brown sugar
- 1 egg, 1 tsp vanilla
- 1/2 tsp baking soda, pinch of salt
- 1/2 cup dark chocolate chips

Method
1. Cream butter and sugar. Beat in egg and vanilla.
2. Fold in flour, baking soda, salt and chips.
3. Scoop onto a tray and bake at 180C for 10-12 minutes.

────────────────────────────
8. Buckwheat Smoothie
────────────────────────────
A quick post-workout drink using Tartary buckwheat flour or sprouted groats.

Ingredients
- 1 banana, 1 cup milk, 2 tbsp Tartary buckwheat flour (toasted)
- 1 tsp honey, 1 tsp peanut butter, ice

Method
Blend everything for 30 seconds. Serve cold.

