3. Buckwheat Kheer (Phaphar Ki Kheer)
────────────────────────────
A creamy, comforting Pakistani-style dessert.

Ingredients
- 1/2 cup whole Tartary buckwheat groats, rinsed
- 4 cups full-cream milk
- 4 tbsp sugar or gur
- 4 crushed cardamoms
- 2 tbsp chopped almonds and pistachios

Method
1. Simmer groats in milk on low heat for 25-30 minutes, stirring often.
2. Add sugar and cardamom. Cook another 5 minutes until thick.
3. Top with nuts. Serve warm or chilled.

────────────────────────────
4. Kuttu Pakoray (Buckwheat Fritters)
────────────────────────────
Perfect for chai time and completely gluten-free.

Ingredients
- 1 cup Tartary buckwheat flour
- 1 chopped potato, 1 chopped onion, 1 green chili
- 1/2 tsp cumin, 1/2 tsp red chili, salt to taste
- Water to make a thick batter
- Oil for frying

Method
1. Mix everything into a thick batter.
2. Deep-fry small spoonfuls on medium heat until crisp and golden.
3. Serve with imli chutney or pudina raita.

────────────────────────────
5. Overnight Tartary Buckwheat Breakfast Bowl
────────────────────────────
A no-cook breakfast packed with rutin and fiber.

Ingredients
- 1/2 cup Tartary buckwheat groats
- 1 cup yogurt or milk
- 1 tbsp honey
- Sliced banana, berries, chopped nuts

Method
1. Soak groats in yogurt/milk overnight in the fridge.
2. In the morning, stir in honey and top with fruit and nuts.

────────────────────────────
6. Buckwheat & Vegetable Khichdi
────────────────────────────
A one-pot desi meal — hearty, warming and gut-friendly.

Ingredients
- 1 cup Tartary buckwheat groats
- 1/2 cup moong daal
- Chopped carrots, peas, tomato
- 1 tsp cumin, 1/2 tsp turmeric, salt
- 1 tbsp ghee
- 4 cups water

Method
1. Heat ghee, splutter cumin, add vegetables and spices.
2. Add rinsed buckwheat and daal with water.
3. Pressure cook for 3 whistles or simmer 25 minutes. Serve with dahi.

