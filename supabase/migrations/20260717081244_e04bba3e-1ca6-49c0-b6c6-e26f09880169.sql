Cooking Tips for Himalayan Tartary Buckwheat
────────────────────────────
- Always rinse whole groats before cooking — it removes the natural bitterness.
- For rotis, add a boiled potato or a little arrowroot to bind the dough.
- Toast the flour lightly on a dry tawa before making smoothies or pancakes to enhance the nutty flavor.
- Store flour in an airtight jar in a cool, dry place — buckwheat is oil-rich and can turn rancid if exposed.

